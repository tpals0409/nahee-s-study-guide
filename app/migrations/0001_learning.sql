CREATE TABLE attempts (
	seq INTEGER PRIMARY KEY AUTOINCREMENT,
	t INTEGER NOT NULL,
	id TEXT NOT NULL,
	ok INTEGER NOT NULL,
	amb INTEGER NOT NULL DEFAULT 0,
	UNIQUE (t, id)
);

CREATE TABLE days (
	day TEXT PRIMARY KEY,
	ids TEXT NOT NULL,
	extra TEXT NOT NULL DEFAULT '[]',
	c INTEGER NOT NULL
);

CREATE TABLE flags (
	id TEXT PRIMARY KEY,
	active INTEGER NOT NULL,
	t INTEGER NOT NULL
);
