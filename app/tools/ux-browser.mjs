// Run after npm run build. Browser dependency/executable are supplied by the QA host.
// All requests are fulfilled locally; no production account or AI request is used.
import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, extname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const args = Object.fromEntries(process.argv.slice(2).map(a => a.replace(/^--/, '').split('=')));
const { chromium } = await import(pathToFileURL(args.module).href);
const root = fileURLToPath(new URL('../', import.meta.url));
const assets = resolve(root, '.cloudflare/output/v0/workers/default/assets');
const output = args.output || '/tmp/study-ux';
await mkdir(output, { recursive: true });
const questions = JSON.parse(await readFile(resolve(root, 'public/questions.json'), 'utf8'));
const day = new Date().toLocaleDateString('en-CA', {timeZone:'Asia/Seoul'});
const sample = ['산업재산권법','민법개론','자연과학개론'].flatMap(subject => questions.filter(q => q.subject === subject).slice(0,4));
const seed = {log:[], days:{[day]:{ids:sample.map(q => q.id), c:Date.now()}}, flags:{}};
const browser = await chromium.launch({headless:true, executablePath:args.browser});
const report = [];
try {
 for (const [width,height] of [[390,844],[768,1024],[1024,768],[1180,820]]) {
  const context = await browser.newContext({viewport:{width,height}, serviceWorkers:'block', reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  let failQuestions = false, failChat = false, explainStatus = 200;
  await page.route('**/*', async route => {
   const url = new URL(route.request().url());
   if (url.hostname !== 'study.test') return route.abort();
   if (url.pathname === '/questions.json' && failQuestions) return route.abort();
   if (url.pathname === '/api/sync') return route.fulfill({json:{log:[],days:{},flags:{},cursor:0,epoch:1}});
   if (url.pathname === '/api/auth/logout') return route.fulfill({json:{ok:true}});
   if (url.pathname === '/api/explain') return route.fulfill({status:explainStatus,json:{summary:'핵심 요건을 먼저 확인해요.', choices:Array(5).fill('요건과 사실관계를 대조하면 판단할 수 있어요.'), basis:[]}});
   if (url.pathname === '/api/ask') return route.fulfill({status:failChat?503:200, contentType:'text/plain', body:failChat?'unavailable':'먼저 핵심 요건을 확인해요.\n\n'.repeat(60)});
   const path = resolve(assets, url.pathname === '/' ? 'index.html' : '.' + url.pathname);
   if (!path.startsWith(assets + '/')) return route.abort();
   try { await route.fulfill({body:await readFile(path), contentType:({'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json','.png':'image/png','.webp':'image/webp','.webmanifest':'application/manifest+json'})[extname(path)] || 'application/octet-stream'}); }
   catch { await route.fulfill({status:404,body:'not found'}); }
  });
  const capture = async name => {
   await page.waitForTimeout(60);
   const geometry = await page.evaluate(() => ({width:innerWidth, scrollWidth:document.documentElement.scrollWidth, height:innerHeight, scrollHeight:document.documentElement.scrollHeight, heading:document.querySelector('.main h1')?.getBoundingClientRect().toJSON()}));
   assert.ok(geometry.scrollWidth <= width + 1, `${name}: horizontal overflow`);
   const overview = ['home','home-complete','notes-empty','notes-filled','stats-empty','stats-filled','calendar','radar-0','radar-1','radar-2','radar-3','exam'].includes(name);
   if(overview && width>=768) assert.ok(geometry.scrollHeight<=height,`${name}: unnecessary tablet scroll`);
   if(overview) assert.equal(geometry.heading?.y,width>=768?32:76,`${name}: main heading alignment`);
   await page.screenshot({path:resolve(output,`${width}-${name}.png`)});
   report.push({width,height,name,...geometry});
  };
  await page.goto('https://study.test/');
  await page.getByRole('button',{name:'Google 계정으로 로그인'}).waitFor();
  await capture('login');
  await page.evaluate(state => {localStorage.setItem('signedIn','true');localStorage.setItem('state',JSON.stringify(state));},seed);
  await page.reload();
  await page.locator('[data-act=daily]').waitFor();
  await capture('home');
  await page.locator('[data-tab=notes]').click();
  await capture('notes-empty');
  await page.locator('[data-act=notes-empty]').first().click();
  assert.equal(new URL(page.url()).hash,'#notes');
  await page.locator('[data-tab=stats]').click();
  await capture('stats-empty');
  for (let i=0;i<4;i++) { await page.locator(`[data-act=radar-select][data-index="${i}"]`).click(); await capture(`radar-${i}`); if(width===768) assert.ok((await page.locator('.radar-card svg').boundingBox()).width>=280,'portrait plot must remain legible'); }
  await page.locator('[data-view=calendar]').click();
  await capture('calendar');
  await page.locator('[data-act=month][data-delta="-1"]').click();
  await page.locator('[data-act=record-day]').first().click();
  await page.locator('[data-tab=home]').click();
  await page.locator('[data-act=daily]').click();
  assert.equal(await page.locator('#reveal-answer').isDisabled(),true);
  await capture('daily');
  if(await page.locator('.zoomable').count()) {
   await page.locator('.figure summary').click();
   await page.locator('.zoomable').first().click();
   await capture('image-zoom');
   await page.locator('#zoom [data-act=dialog-close]').click();
  }
  await page.locator('.choice').first().click();
  assert.equal(await page.locator('#reveal-answer').isDisabled(),false);
  await page.locator('[data-act=amb]').click();
  await page.locator('[data-act=reveal]').click();
  if(width<768) await page.locator('[data-act=sheet-open]').click();
  await page.locator('[data-act=ai-chat-open]').waitFor();
  await capture('explanation');
  await page.locator('[data-act=ai-chat-open]').click();
  await page.locator('[data-act=chat-prompt]').first().click();
  assert.ok((await page.locator('#ask').inputValue()).length>0);
  assert.ok(await page.locator('#ai-chat').evaluate(d=>d.open));
  await capture('chat-empty');
  await page.locator('#ask').press('Control+Enter');
  await page.locator('.chat-status').filter({hasText:'완료'}).waitFor();
  await page.locator('.chat-messages').evaluate(el=>el.scrollTop=0);
  await page.locator('.chat-latest').waitFor({state:'visible'});
  await page.locator('.chat-latest').click();
  await capture('chat-answer');
  failChat=true;
  await page.locator('#ask').fill('실패해도 보존할 질문');
  await page.locator('#ask').press('Control+Enter');
  await page.locator('.chat-status').filter({hasText:'받지 못했어요'}).waitFor();
  assert.equal(await page.locator('#ask').inputValue(),'실패해도 보존할 질문');
  await capture('chat-error');
  await page.locator('#ai-chat [data-act=dialog-close]').click();
  if(width<768) await page.locator('button[data-act=sheet-close]').click();
  await page.locator('[data-act=close]').click();
  await page.locator('[data-tab=notes]').click();
  const topicLink = page.locator('.notes-part[href]').first();
  if(await topicLink.count()) { await topicLink.click(); await capture('notes-topic'); await page.locator('[data-act=topic-review][data-due=true]').click(); await capture('review'); await page.locator('[data-act=close]').click(); }
  await page.locator('[data-tab=exam]').click();
  await capture('exam');
  await page.locator('[data-act=round-toggle]').click();
  await capture('round-sheet');
  await page.keyboard.press('Escape');
  await page.locator('[data-act=round]').first().click();
  await capture('exam-intro');
  await page.locator('[data-act=round-start]').click();
  await page.locator('.choice').first().click();
  assert.equal(await page.locator('[data-act=reveal]').count(),0);
  await capture('mock');
  await page.locator('[data-act=mock-map]').click();
  await capture('question-map');
  await page.locator('[data-act=mock-go]').nth(2).click();
  await page.locator('[data-act=mock-submit]').click();
  await capture('submit-confirm');
  await page.locator('[data-act=mock-confirm]').click();
  await capture('mock-result');
  await page.locator('[data-act=mock-filter][data-filter=skip]').click();
  await page.locator('[data-act=mock-review]').first().click();
  await capture('mock-review');
  await page.locator('[data-act=mock-result]').click();
  await page.locator('[data-act=leave]').click();
  await page.locator('[data-tab=stats]').click();
  await page.locator('[data-view=accuracy]').click();
  await capture('stats-filled');
  failQuestions=true;
  await page.reload();
  await page.locator('[data-act=reload-app]').waitFor();
  await capture('load-error');
  failQuestions=false;
  await page.locator('[data-act=reload-app]').click();
  await page.locator('.main').waitFor();
  // Seed deterministic local history to cover less-frequent notebook and completion states.
  const parts = [...new Map(questions.filter(q=>q.topic && q.topic!=='기타').map(q=>[q.subject+'|'+q.topic,q])).values()];
  const populated = { ...seed, log:parts.map((q,i)=>({id:q.id,ok:false,t:Date.now()-86400000+i})), flags:{[sample[0].id]:{on:true,t:Date.now()}} };
  await page.evaluate(state=>{localStorage.setItem('state',JSON.stringify(state));localStorage.removeItem('session');location.hash='#notes';},populated);
  await page.reload();
  await page.locator('.notes-summary').waitFor();
  await capture('notes-filled');
  await page.locator('.notes-part[href]').first().click();
  await capture('notes-topic');
  await page.locator('[data-act=topic-review][data-due=true]').click();
  await capture('review');
  await page.locator('[data-act=close]').click();
  await page.locator('[data-tab=notes]').click();
  for(const subject of ['민법개론','자연과학개론']) {await page.locator(`[data-act=notes-subject][data-subject="${subject}"]`).click();await capture(`notes-${subject}`);}
  await page.locator('.notes-flagged a').click();
  await capture('notes-flagged');
  await page.locator('[data-act=single]').first().click();
  assert.equal(await page.locator('[data-act=flag]').getAttribute('aria-pressed'),'true');
  await page.locator('[data-act=flag]').click();
  await page.locator('.choice').first().click();
  await page.locator('[data-act=reveal]').click();
  await page.locator('[data-act=next]').click();
  await capture('learning-complete');
  await page.locator('[data-act=leave]').click();
  const completed={...seed,log:sample.map((q,i)=>({id:q.id,ok:true,t:Date.now()+i}))};
  await page.evaluate(state=>{localStorage.setItem('state',JSON.stringify(state));localStorage.removeItem('session');location.hash='#home';},completed);
  await page.reload();
  await page.locator('[data-act=more]').waitFor();
  await capture('home-complete');
  await page.locator('[data-act=more]').click();
  await capture('extra-intro');
  await page.locator('[data-act=more-start]').click();
  await capture('extra-solve');
  await page.locator('[data-act=close]').click();
  // Original image, explanation failure/retry, and modal focus on a deterministic single question.
  const imageQuestion = questions.find(q=>q.images?.length);
  const singleSession = {mode:'single',ids:[imageQuestion.id],i:0,title:'다시 풀기',orders:[[imageQuestion.id,[0,1,2,3,4]]],picks:{},score:0,from:'#home'};
  await page.evaluate(saved=>{localStorage.setItem('session',JSON.stringify(saved));},singleSession);
  await page.reload();
  await page.locator('.zoomable').first().click();
  await capture('image-zoom');
  await page.keyboard.press('Escape');
  await page.locator('.choice').first().click();
  explainStatus=503;
  await page.locator('[data-act=reveal]').click();
  if(width<768) await page.locator('[data-act=sheet-open]').click();
  await page.locator('[data-act=retry]').waitFor();
  await capture('explanation-error');
  explainStatus=200;
  await page.locator('[data-act=retry]').click();
  await page.locator('[data-act=ai-chat-open]').waitFor();
  await page.locator('[data-act=ai-chat-open]').click();
  assert.ok(await page.locator('#ai-chat').evaluate(d=>d.contains(document.activeElement)));
  await page.locator('#ask').fill('회전해도 남는 질문');
  await page.setViewportSize({width:width>=1024?768:1024,height});
  assert.equal(await page.locator('#ask').inputValue(),'회전해도 남는 질문');
  await page.setViewportSize({width,height});
  await page.keyboard.press('Escape');
  if(width<768) await page.locator('button[data-act=sheet-close]').click();
  await page.locator('[data-act=close]').click();
  await page.locator('button[data-act=logout]:visible').click();
  await capture('logout-confirm');
  await page.locator('[data-act=logout-confirm]').click();
  await page.getByRole('button',{name:'Google 계정으로 로그인'}).waitFor();
  assert.equal(await page.locator('dialog[open]').count(),0);
  assert.deepEqual(errors,[],`${width}: runtime errors`);
  console.log(`${width}×${height}: primary journeys and error recovery passed`);
  await context.close();
 }
 await writeFile(resolve(output,'report.json'),JSON.stringify(report,null,2));
} finally { await browser.close(); }
