from collect_laws import article_key, article_text, in_force, intervals, reverted, treaty_text

# 항 없는 조문, 항·호·목, 목록으로 온 내용
assert article_text({"조문내용": "제1조(목적) 이 법은"}) == "제1조(목적) 이 법은"
unit = {"조문내용": "제2조(정의)", "항": {"호": [{"호내용": "1. 가", "목": [{"목내용": ["가. 나", "나. 다"]}]}, {"호내용": "2. 라"}]}}
assert article_text(unit) == "제2조(정의)\n1. 가\n가. 나\n나. 다\n2. 라"
assert article_key({"조문번호": "0052", "조문가지번호": "02"}) == "52의2"
assert article_key({"조문번호": "110", "조문가지번호": ""}) == "110"

# 2008년 당시 판부터, 같은 시행일은 늦게 공포된 판, 미래 시행일 제외
row = lambda day, pub, mst: {"시행일자": day, "공포일자": pub, "법령일련번호": mst}
rows = [row("20050101", "20040101", "1"), row("20070101", "20060101", "2"), row("20130701", "20110519", "3"),
        row("20130701", "20130405", "4"), row("20270101", "20260101", "5")]
assert [r["법령일련번호"] for r in in_force(rows, "20261106")] == ["2", "4"]

# 공백만 바뀌면 구간 유지, 본문이 바뀌면 나누고, 사라지면 닫는다
articles = intervals([
    ("20080101", {"1": ("가", "제1조 a"), "2": ("나", "제2조 b")}),
    ("20100101", {"1": ("가", "제1조  a"), "2": ("나", "제2조 c")}),
    ("20120101", {"1": ("가", "제1조 a")}),
])
assert len(articles["1"]) == 1 and articles["1"][0]["to"] is None
assert [(s["from"], s["to"]) for s in articles["2"]] == [("20080101", "20100101"), ("20100101", "20120101")]

# 개정 표시만 바뀐 판은 본문 변경이 아니다
marked = intervals([("1", {"1": ("", "제1조 a <개정 2010.1.27>")}), ("2", {"1": ("", "제1조 a <개정 2011.1.1> [전문개정 2011.1.1]")})])
assert len(marked["1"]) == 1

# 없어졌다가 다시 생긴 조문은 새 구간
again = intervals([("1", {"1": ("", "a")}), ("2", {}), ("3", {"1": ("", "b")})])
assert [(s["from"], s["to"]) for s in again["1"]] == [("1", "2"), ("3", None)]

assert reverted(intervals([("1", {"1": ("", "a")}), ("2", {"1": ("", "b")}), ("3", {"1": ("", "a")})])) == ["1"]
# 조약 표시는 지우고 소제목은 남기며, 지정 구간만 자른다
wrap = lambda s: {"MultTrtyService": {"조약내용": {"조약내용": s}}}
assert treaty_text(wrap("[조약번호]가[/조약번호][본문]제1조 [ 납부 ] 나[/본문]")) == "가\n\n제1조 [ 납부 ] 나"
assert treaty_text(wrap("앞[조약번호]가[/조약번호]나[조약번호]다"), ("[조약번호]가", "[조약번호]다")) == "가\n나"
print("law ok")
